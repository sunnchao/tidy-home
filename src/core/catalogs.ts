export function getItemSpritePool(itemId: string): ResolvedItemSprite[] {
  const def = ITEM_BY_ID[itemId];
  if (!def) {
    return [
      {
        spriteResource: `sprites/${itemId}`,
        spriteWebUrl: `/resources/sprites/${itemId}.png`,
        pose: 'flat',
        aspectRatio: 1,
      },
    ];
  }
  const baseAspect = def.aspectRatio ?? 1;
  const baseEntry: ResolvedItemSprite = {
    spriteResource: def.spriteResource,
    spriteWebUrl: def.spriteWebUrl,
    pose: 'flat',
    aspectRatio: baseAspect,
  };
  if (!def.variants || def.variants.length === 0) {
    return [baseEntry];
  }
  return [
    baseEntry,
    ...def.variants.map((variant) => ({
      spriteResource: variant.spriteResource,
      spriteWebUrl: variant.spriteWebUrl,
      pose: variant.pose ?? ('flat' as ItemPose),
      aspectRatio: variant.aspectRatio ?? baseAspect,
    })),
  ];
}

export function getItemSprite(itemId: string, variantIndex = 0): ResolvedItemSprite {
  const pool = getItemSpritePool(itemId);
  const normalized = ((Math.trunc(variantIndex) % pool.length) + pool.length) % pool.length;
  return pool[normalized];
}

export function getAllSpriteResources(): string[] {
  const seen = new Set<string>(['sprites/cardboard_closed', 'sprites/cardboard_cracked']);
  for (const item of ITEM_CATALOG) {
    seen.add(item.spriteResource);
    if (item.variants) {
      for (const variant of item.variants) {
        seen.add(variant.spriteResource);
      }
    }
  }
  return Array.from(seen);
}
